#!/usr/bin/env python3
"""coverage.py [--write]  -- how much of each area of the code has a name.

Counts functions from ghidra_funcs.tsv against names.tsv + symbols/*.tsv, grouped by the
address ranges in AREAS below. With --write, rewrites docs/STATUS.md."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import symtab

ROOT = symtab.ROOT
# (start, end, id, what is in it)  -- ranges are approximate; refine them as areas get mapped
AREAS = [
    (0x100000, 0x109d68, 'startup',   'picture cache, items, creature helpers'),
    (0x109d68, 0x131d88, 'creatures', 'Creature base class, AI helpers, per-class clone functions'),
    (0x131d88, 0x13ecf8, 'netcode',   'lockstep loop, prediction, input codec, peers, game messages'),
    (0x13ecf8, 0x147300, 'script',    'level-script VM and its 191 built-in commands'),
    (0x147300, 0x160000, 'objects',   'GameObject, world grid and lists, memory pool, props'),
    (0x160000, 0x1a0000, 'engine',    'math, animation, lump files, pads, model drawing, text, terrain, pathfinding, camera, dialog, particles, cutscenes, tasks'),
    (0x1a0000, 0x1c0000, 'player',    'Player class, player record, inventory items, stats'),
    (0x1c0000, 0x1e8000, 'ui',        'inventory and menus, HUD, shop, game state'),
    (0x1e8000, 0x210000, 'gameplay',  'damage, triggers, effects, world camera, vehicles'),
    (0x210000, 0x232000, 'audio-save', 'sound, save and load, mission menu, store'),
    (0x232000, 0x2c3cd4, 'monsters',  'monster classes and level objects (chests, traps, gates, savepoints)'),
    (0x2c3cd4, 0x320000, 'skills',    'Skill and Spell classes'),
    (0x320000, 0x323dcc, 'mainloop',  'task scheduler and main loop'),
    (0x323dcc, 0x3b0000, 'netlib',    'lobby client, SOE UdpLibrary, AES, Sony SDK libraries'),
    (0x3b0000, 0x3e6000, 'runtime',   'C and C++ runtime, type info, static constructors'),
]


def main():
    names = symtab.load()
    funcs = []
    for l in open(os.path.join(ROOT, 'ghidra_funcs.tsv'), encoding='utf-8-sig'):
        ent, name, body = l.rstrip('\n').split('\t')
        size = 0
        for r in body.split(','):
            if r:
                a, b = (int(x, 16) for x in r.split('-'))
                size += b - a + 1
        funcs.append((int(ent, 16), size))
    rows, tot = [], [0, 0, 0, 0]
    for lo, hi, aid, what in AREAS:
        fs = [(a, s) for a, s in funcs if lo <= a < hi]
        named = [(a, s) for a, s in fs if a in names]
        nb, tb = sum(s for _, s in named), sum(s for _, s in fs)
        rows.append((aid, lo, hi, len(fs), len(named), 100.0 * nb / tb if tb else 0.0, what))
        tot[0] += len(fs); tot[1] += len(named); tot[2] += nb; tot[3] += tb
    lines = ['| Area | Address range | Functions | Named | Named, by code size | Contents |', '|---|---|---|---|---|---|']
    for aid, lo, hi, n, k, pct, what in rows:
        lines.append('| %s | %06x–%06x | %d | %d | %.0f%% | %s |' % (aid, lo, hi, n, k, pct, what))
    lines.append('| **all** | | %d | %d | %.0f%% | |' % (tot[0], tot[1], 100.0 * tot[2] / tot[3]))
    table = '\n'.join(lines)
    print(table)
    if '--write' in sys.argv:
        with open(os.path.join(ROOT, 'docs', 'STATUS.md'), 'w', encoding='utf-8', newline='\n') as f:
            f.write('# Status\n\nGenerated by `python3 tools/coverage.py --write`. A function counts as named when its\n'
                    'entry address appears in `names.tsv` or `symbols/*.tsv`. Named is not the same as\n'
                    'understood: see the area document in `docs/` for what has actually been read.\n\n' + table + '\n')


if __name__ == '__main__':
    main()
